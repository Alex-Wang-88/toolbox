def load_base_module():
    spec = importlib.util.spec_from_file_location("datacenter_security_dialogue_base", BASE_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"无法加载基础生成器: {BASE_PATH}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def configure_base(module):
    module.DIALOGUE = AUDIT_DIALOGUE
    module.OUTPUT_DIR = ROOT / "output" / "datacenter_security_audit_40m"
    module.SEGMENTS_DIR = module.OUTPUT_DIR / "segments"
    module.SCRIPT_JSONL = ROOT / "test_inputs" / "datacenter_security_audit_40m.jsonl"
    module.MANIFEST_PATH = module.OUTPUT_DIR / "manifest.json"
    module.WORKER_LOG = module.OUTPUT_DIR / "cosyvoice3_worker.log"
    module.FULL_WAV = module.OUTPUT_DIR / "datacenter_security_audit_40m_full.wav"
    module.FULL_MP3 = module.OUTPUT_DIR / "datacenter_security_audit_40m_full.mp3"
    module.ENGINE_NAME = "datacenter_security_audit_40m_cosyvoice3"


def main() -> int:
    parser = argparse.ArgumentParser(description="生成数据中心入企信息数据安全审查录音")
    parser.add_argument("--smoke", action="store_true", help="每个音色只生成一段样本")
    args = parser.parse_args()
    base = load_base_module()
    configure_base(base)
    return base.generate(smoke=args.smoke)


