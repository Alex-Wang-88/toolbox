def voice_profiles() -> dict[str, dict]:
    """从项目现有音色注册表取参考音频和逐字稿。"""
    voices_path = ROOT / "app_data" / "voices" / "voices.json"
    payload = json.loads(voices_path.read_text(encoding="utf-8"))
    by_id = {item.get("id"): item for item in payload.get("voices", [])}
    profiles = {}
    for voice_id in (MANBO_ID, CHANGKAI_ID):
        meta = by_id.get(voice_id)
        if not meta:
            raise RuntimeError(f"音色注册表中找不到 {voice_id}")
        ref_audio = Path(str(meta.get("ref_audio") or ""))
        if not ref_audio.is_absolute():
            ref_audio = ROOT / "app_data" / "voices" / ref_audio
        if not ref_audio.is_file() and voice_id == CHANGKAI_ID:
            ref_audio = ROOT / "test_inputs" / "voice_changkai_clip8s.wav"
        if not ref_audio.is_file():
            raise FileNotFoundError(f"参考音频不存在: {ref_audio}")
        profiles[voice_id] = {
            "voice_id": voice_id,
            "voice_name": meta.get("name", voice_id),
            "ref_audio": ref_audio,
            "ref_text": str(meta.get("ref_text") or "").strip(),
        }
    if len(profiles[CHANGKAI_ID]["ref_text"]) < 2:
        raise RuntimeError("常凯申音色缺少 CosyVoice3 参考文本")
    return profiles


