def concatenate_wavs(records: list[dict], output: Path, seed: int = 20260907) -> dict:
    paths = [output_path(record) for record in records]
    if not paths or any(not is_valid_wav(path) for path in paths):
        raise RuntimeError("存在缺失或无效的逐段音频，暂不拼接")
    first = wav_info(paths[0])
    expected = (first["channels"], first["sample_width"], first["sample_rate"])
    rng = random.Random(seed)
    pauses = [round(rng.uniform(0.45, 1.15), 2) for _ in range(len(paths) - 1)]
    output.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(output), "wb") as out:
        out.setnchannels(first["channels"])
        out.setsampwidth(first["sample_width"])
        out.setframerate(first["sample_rate"])
        for index, path in enumerate(paths):
            info = wav_info(path)
            actual = (info["channels"], info["sample_width"], info["sample_rate"])
            if actual != expected:
                raise RuntimeError(f"音频格式不一致: {path} {actual} != {expected}")
            with wave.open(str(path), "rb") as source:
                out.writeframes(source.readframes(source.getnframes()))
            if index < len(pauses):
                silence_frames = int(first["sample_rate"] * pauses[index])
                silence = b"\x00" * silence_frames * first["channels"] * first["sample_width"]
                out.writeframes(silence)
    info = wav_info(output)
    info["pause_seed"] = seed
    info["pause_range_sec"] = [0.45, 1.15]
    return info


def encode_mp3(source: Path, target: Path) -> None:
    ffmpeg = ROOT / "bin" / "ffmpeg" / "ffmpeg.exe"
    command = [
        str(ffmpeg),
        "-y",
        "-hide_banner",
        "-loglevel",
        "error",
        "-i",
        str(source),
        "-codec:a",
        "libmp3lame",
        "-b:a",
        "96k",
        str(target),
    ]
    result = subprocess.run(command, capture_output=True, text=True, timeout=600)
    if result.returncode != 0 or not target.is_file() or target.stat().st_size < 1000:
        raise RuntimeError(f"MP3 编码失败: {result.stderr[-1000:]}")


def generate(smoke: bool = False) -> int:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    SEGMENTS_DIR.mkdir(parents=True, exist_ok=True)
    records = build_records()
    profiles = voice_profiles()
    write_script(records)
    statuses: dict[str, dict] = {}
    groups: dict[str, list[dict]] = defaultdict(list)
    for record in records:
        groups[record["voice_id"]].append(record)

    selected_groups = {
        voice_id: group[:1] if smoke else group for voice_id, group in groups.items()
    }
    MultiTtsWorkerClient, client = build_client()
    try:
        print(f"[START] 输出目录: {OUTPUT_DIR}", flush=True)
        print(f"[START] 轮数/段数: {len(DIALOGUE)}/{len(records)}", flush=True)
        print(f"[START] 稿件字符数: {sum(len(x['text']) for x in records)}", flush=True)
        print(f"[START] 模型: {MODEL_DIR}", flush=True)
        print(f"[START] 模式: {'smoke' if smoke else 'full'}", flush=True)

        for voice_id, group in selected_groups.items():
            profile = profiles[voice_id]
            pending = []
            for record in group:
                path = output_path(record)
                if is_valid_wav(path):
                    statuses[record["segment_id"]] = {"status": "existing"}
                else:
                    pending.append(
                        {
                            "segment_id": record["segment_id"],
                            "text": record["text"],
                            "output_path": str(path),
                            "mode": record["synthesis_mode"],
                            "instruction": record["instruction"],
                            "language": record["language"],
                            "language_code": record["language_code"],
                        }
                    )
            print(
                f"[GROUP] {profile['voice_name']} / {voice_id}: "
                f"待生成 {len(pending)}，已存在 {len(group) - len(pending)}",
                flush=True,
            )
            if not pending:
                continue
            client.set_ref_text(profile["ref_text"])
            started = time.time()
            result = client.synthesize(
                pending,
                ref_audio_path=str(profile["ref_audio"]),
                speed=1.0,
                ref_text=profile["ref_text"],
                cache_keys=None,
            )
            elapsed = round(time.time() - started, 1)
            result_by_id = {str(item.get("segment_id")): item for item in result}
            for item in pending:
                sid = str(item["segment_id"])
                one = result_by_id.get(sid, {})
                path = Path(item["output_path"])
                if one.get("ok") and is_valid_wav(path):
                    statuses[sid] = {
                        "status": "generated",
                        "elapsed_sec": elapsed,
                        "worker_result": one,
                    }
                    print(f"[OK] {sid} {wav_info(path)['duration_sec']}s", flush=True)
                else:
                    statuses[sid] = {
                        "status": "failed",
                        "error": one.get("error", "Worker 未返回有效音频"),
                        "worker_result": one,
                    }
                    print(f"[ERROR] {sid}: {statuses[sid]['error']}", flush=True)
            write_manifest(records, statuses, profiles)

        if smoke:
            write_manifest(records, statuses, profiles)
            ok = sum(1 for item in statuses.values() if item.get("status") in {"generated", "existing"})
            print(f"[SMOKE DONE] 有效样本 {ok}/2", flush=True)
            return 0 if ok == 2 else 2

        missing = [record for record in records if not is_valid_wav(output_path(record))]
        if missing:
            write_manifest(records, statuses, profiles)
            print(f"[STOP] 仍有 {len(missing)} 段没有有效音频，暂不拼接完整文件。", flush=True)
            return 2

        full_info = concatenate_wavs(records, FULL_WAV)
        encode_mp3(FULL_WAV, FULL_MP3)
        write_manifest(records, statuses, profiles, full_audio=FULL_WAV, mp3_audio=FULL_MP3)
        print(
            f"[DONE] WAV: {FULL_WAV} | MP3: {FULL_MP3} | "
            f"时长 {full_info['duration_sec']:.2f}s ({full_info['duration_sec'] / 60:.2f}min)",
            flush=True,
        )
        return 0
    finally:
        try:
            MultiTtsWorkerClient.shutdown_instance(ENGINE_NAME)
        except Exception as exc:
            print(f"[WARN] Worker 释放异常: {exc}", flush=True)


def main() -> int:
    parser = argparse.ArgumentParser(description="生成双人数据中心安全问答测试录音")
    parser.add_argument("--smoke", action="store_true", help="每个音色只生成一段样本")
    args = parser.parse_args()
    return generate(smoke=args.smoke)


